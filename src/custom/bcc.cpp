void find_clib_signatures(Bit8u* p_cs, Bit8u* p_ds)
{
	const char outstring[] = "Found at CS:0x%04lx Func: %20s Length: 0x%04lx Versions: %s\n";
	const unsigned long len = p_ds - p_cs;	/* Size in bytes of the area between CS and DS */
	long unsigned i = 0;

	if (p_ds <= p_cs) return;

	while (i < len) {
		if (memcmp(p_cs + i, s_strlen, sizeof(s_strlen)) == 0) {
			fprintf(stderr, outstring, i, "strlen()", sizeof(s_strlen), "BCC 2.0, 3.1");
			i += sizeof(s_strlen) - 1;
		}
		if (memcmp(p_cs + i, s_bioskey20, sizeof(s_bioskey20)) == 0) {
			fprintf(stderr, outstring, i, "bioskey()", sizeof(s_bioskey20), "BCC 2.0");
			i += sizeof(s_bioskey20) - 1;
		}
		if (memcmp(p_cs + i, s_bioskey31, sizeof(s_bioskey31)) == 0) {
			fprintf(stderr, outstring, i, "bioskey()", sizeof(s_bioskey31), "BCC 3.1");
			i += sizeof(s_bioskey31) - 1;
		}
		if (memcmp(p_cs + i, s_memcpy, sizeof(s_memcpy)) == 0) {
			fprintf(stderr, outstring, i, "memcpy()", sizeof(s_memcpy), "BCC 2.0, 3.1");
			i += sizeof(s_memcpy) - 1;
		}
		if (memcmp(p_cs + i, s_setmem, sizeof(s_setmem)) == 0) {
			fprintf(stderr, outstring, i, "setmem() (internal)", sizeof(s_setmem), "BCC 2.0, 3.1");
			i += sizeof(s_setmem) - 1;
		}
		if (memcmp(p_cs + i, s_memset, sizeof(s_memset)) == 0) {
			fprintf(stderr, outstring, i, "memset()", sizeof(s_memset), "BCC 2.0, 3.1");
			i += sizeof(s_memset) - 1;
		}
		if (memcmp(p_cs + i, s__rotl, sizeof(s__rotl)) == 0) {
			fprintf(stderr, outstring, i, "_rotl()" , sizeof(s__rotl), "BCC 2.0, 3.1");
			i += sizeof(s__rotl) - 1;
		}
		if (memcmp(p_cs + i, s_abs, sizeof(s_abs)) == 0) {
			fprintf(stderr, outstring, i, "abs()" , sizeof(s_abs), "BCC 2.0, 3.1");
			i += sizeof(s_abs) - 1;
		}
		if (memcmp(p_cs + i, s_flxmul, sizeof(s_flxmul)) == 0) {
			fprintf(stderr, outstring, i, "F_LXMUL" , sizeof(s_flxmul), "BCC 2.0, 3.1");
			i += sizeof(s_flxmul) - 1;
		}
		if (memcmp(p_cs + i, s_flxrsh, sizeof(s_flxrsh)) == 0) {
			fprintf(stderr, outstring, i, "F_LXRSH" , sizeof(s_flxrsh), "BCC 2.0, 3.1");
			i += sizeof(s_flxrsh) - 1;
		}
		if (memcmp(p_cs + i, s_fpada, sizeof(s_fpada)) == 0) {
			fprintf(stderr, outstring, i, "F_PADA" , sizeof(s_fpada), "BCC 2.0, 3.1");
			i += sizeof(s_fpada) - 1;
		}
		if (memcmp(p_cs + i, s_fpadd, sizeof(s_fpadd)) == 0) {
			fprintf(stderr, outstring, i, "F_PADD" , sizeof(s_fpadd), "BCC 2.0, 3.1");
			i += sizeof(s_fpadd) - 1;
		}
		if (memcmp(p_cs + i, s_exit, sizeof(s_exit)) == 0) {
			fprintf(stderr, outstring, i, "exit()" , sizeof(s_exit), "BCC 3.1");
			i += sizeof(s_exit) - 1;
		}
		if (memcmp(p_cs + i, s___dos_open, sizeof(s___dos_open)) == 0) {
			fprintf(stderr, outstring, i, "__dos_open()" , 0x36L, "BCC 3.1");
			i += 0x36 - 1;
		}
		if (memcmp(p_cs + i, s___dos_read, sizeof(s___dos_read)) == 0) {
			fprintf(stderr, outstring, i, "__dos_read()" , 0x24L, "BCC 3.1");
			i += 0x24 - 1;
		}
		if (memcmp(p_cs + i, s___dos_close, sizeof(s___dos_close)) == 0) {
			fprintf(stderr, outstring, i, "__dos_close()" , 0x16L, "BCC 3.1");
			i += 0x16 - 1;
		}
		if (memcmp(p_cs + i, s___IOERROR, sizeof(s___IOERROR)) == 0) {
			fprintf(stderr, outstring, i, "__IOERROR()" , 0x39L, "BCC 2.0, 3.1");
			i += 0x39 - 1;
		}
		if (memcmp(p_cs + i, s___DOSERROR, sizeof(s___DOSERROR)) == 0) {
			fprintf(stderr, outstring, i, "__DOSERROR()" , 0x11L, "BCC 3.1");
			i += 0x11 - 1;
		}
		if (memcmp(p_cs + i, s_heapwalk, sizeof(s_heapwalk)) == 0) {
			/* function is longer than the signature */
			fprintf(stderr, outstring, i, "heapwalk()" , 0x77L, "BCC 2.0, 3.1");
			i += 0x77 - 1;
		}

		i++;
	}
}

bool check_bcc(char *name, unsigned short reloc, unsigned short _cs, unsigned short _ip)
{
	Bit8u* p_datseg = NULL;
	Bit8u *p_cseg = NULL;
	Bit16u datseg;
	const char *sig = NULL;

	fprintf(stderr, "Executable: %s is Checked!\n", name);

	p_cseg = MemBase + PhysMake(reloc + _cs, _ip);

	/* Check CS:IP in the EXE-Header are 0:0
	 * and the first executed instruction is mov dx, i16 */
	if (_cs != 0 || _ip != 0 || *p_cseg != 0xba)
		return false;

	//fprintf(stderr, "Executable: %s passed 1!\n", name);

	/* next two bytes are the segment address of the datasegment */
	datseg = real_readw(reloc, _ip + 1);
	p_datseg = MemBase + PhysMake(datseg, 0);

	/* Check if the start of the Datasegment is Borland C++ */
	if (host_readd(p_datseg) == 0) {
		if (!strcmp((char*)(p_datseg + 4), borsig)) sig = borsig;
		else if (!strcmp((char*)(p_datseg + 4), tcsig)) sig = tcsig;
		else if (!strcmp((char*)(p_datseg + 4), tcpsig)) sig = tcpsig;
	}

	if (sig == NULL) {
		fprintf(stderr, "Executable: %s no known signature found!\n", name);
		return false;
	}

	//fprintf(stderr, "Executable: %s passed 2!\n", name);

	/* Now: more info */
	Bit8u* pt = MemBase + PhysMake(reloc, 0x25); /* pointer to call SaveVectors */
	int version = -1;
	char model = '?';

	/* Borland C++ */
	if ((sig == borsig) && (*pt++ == 0xe8)) {
		//fprintf(stderr, "Executable: %s passed 3!\n", name);
		     if ((pt[0] == 0x43) && (pt[1] == 0x01) && (p_cseg[0x6] == 0x3c) ) {	version = 20; model = 'M'; }
		else if ((pt[0] == 0x14) && (pt[1] == 0x01)) {	version = 20; model = 'C'; }
		else if ((pt[0] == 0x1a) && (pt[1] == 0x01)) {	version = 20; model = 'L'; }
		else if ((pt[0] == 0x08) && (pt[1] == 0x01)) {	version = 20; model = 'H'; }

		else if ((pt[0] == 0x85) && (pt[1] == 0x01)) {	version = 30; model = 'M'; }
		else if ((pt[0] == 0x4e) && (pt[1] == 0x01)) {	version = 30; model = 'C'; }
		else if ((pt[0] == 0x52) && (pt[1] == 0x01)) {	version = 30; model = 'L'; }
		else if ((pt[0] == 0x40) && (pt[1] == 0x01)) {	version = 30; model = 'H'; }

		else if ((pt[0] == 0x88) && (pt[1] == 0x01)) {	version = 31; model = 'M'; }
		else if ((pt[0] == 0x51) && (pt[1] == 0x01)) {	version = 31; model = 'C'; }
		else if ((pt[0] == 0x55) && (pt[1] == 0x01)) {	version = 31; model = 'L'; }
		else if ((pt[0] == 0x43) && (pt[1] == 0x01) && (p_cseg[0x6] == 0x84)) {	version = 31; model = 'H'; }
	}

	fprintf(stderr, "Executable: %s, Compiler: %s\n", name, sig);
	fprintf(stderr, "Executable: %s, Version: %d.%d Model %c!\n", name, version / 10, version % 10, model);

	find_clib_signatures(p_cseg, p_datseg);

	return true;
}
